interface I18nValue {
  lang: LanguageCode;
  setLang: (l: LanguageCode) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("agrisense_lang") as LanguageCode;
      if (saved && (saved === "en" || saved === "kn" || saved === "hi")) {
        return saved;
      }
    }
    return "en";
  });

  const setLang = (l: LanguageCode) => {
    setLangState(l);
    if (typeof window !== "undefined") {
      localStorage.setItem("agrisense_lang", l);
    }
  };

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang, t: (key) => dicts[lang]?.[key] ?? en[key] ?? key }),
    [lang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
